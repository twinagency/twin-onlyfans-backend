import assert from 'node:assert/strict';
import {randomUUID} from 'node:crypto';
import {createSignInService,networkFingerprint} from './service.mjs';
const scope={creatorId:'isolated-creator',actor:'creator-session:'+'a'.repeat(64)};
const proxyUrl='http://fixture:secret@8.8.4.4:12323';
const network={accountId:null,ownerId:null,proxyUrl,fingerprint:networkFingerprint(proxyUrl)};
const flush=()=>new Promise(resolve=>setImmediate(resolve));
let launches=0;
const denied=createSignInService({beforeLaunch:async()=>{throw Error('reservation_reclaimed');},launch:async()=>{launches++;throw Error('must not launch');}});
let attempt=await denied.start(scope,{startKey:randomUUID(),network});
await flush();
assert.equal(denied.status(scope,attempt.id).phase,'failed');
assert.equal(launches,0);
await denied.close();
let resolveGuard,seen;
const pending=createSignInService({beforeLaunch:async(n,s)=>{seen={n,s};await new Promise(resolve=>{resolveGuard=resolve});},launch:async()=>{launches++;throw Error('must not launch after cancel');}});
attempt=await pending.start(scope,{startKey:randomUUID(),network});
assert.deepEqual(seen,{n:network,s:scope});
await pending.cancel(scope,attempt.id);
resolveGuard();await flush();
assert.equal(pending.status(scope,attempt.id).phase,'cancelled');
assert.equal(launches,0);
await pending.close();
console.log('PASS broker guard: refusal and cancellation cannot open a late browser; authenticated scope and fixed network retained.');
